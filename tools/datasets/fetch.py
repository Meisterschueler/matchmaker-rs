"""Download the benchmark datasets at their pinned commits and write bench manifests (T049).

    python fetch.py --dest DIR [--datasets nasap,batik,vienna4x22] [--limit N]

Each dataset is fetched with git at the commit pinned in datasets.toml (shallow, by commit
hash, which also verifies the content) into DIR/<dataset>. The manifest DIR/<dataset>.toml lists
score, performance and ground truth with absolute paths for `matchmaker bench` and
tools/bench/run_reference.py. ``--limit`` keeps N pieces spread evenly over the sorted list
(deterministic) to bound CI time. Standard library only; needs git.
"""

from __future__ import annotations

import argparse
import csv
import subprocess
import tomllib
from pathlib import Path

DATASETS = tomllib.loads((Path(__file__).parent / "datasets.toml").read_text(encoding="utf-8"))


def fetch(repo: str, commit: str, dest: Path) -> None:
    head = subprocess.run(["git", "-C", str(dest), "rev-parse", "HEAD"], capture_output=True, text=True)
    if head.returncode == 0 and head.stdout.strip() == commit:
        return
    dest.mkdir(parents=True, exist_ok=True)
    for args in (
        ["init", "-q"],
        ["fetch", "-q", "--depth", "1", repo, commit],
        ["-c", "advice.detachedHead=false", "checkout", "-q", "FETCH_HEAD"],
    ):
        subprocess.run(["git", "-C", str(dest), *args], check=True)


# (piece, score, performance, ground truth), paths relative to the dataset root
def nasap(root: Path):
    with open(root / "metadata.csv", newline="", encoding="utf-8") as f:
        for row in csv.DictReader(f):
            # only note alignments the (n)ASAP authors marked as robust
            if row["match_file"] and float(row["robust_note_alignment"] or 0) == 1:
                piece = row["midi_performance"].removesuffix(".mid").replace("/", "_")
                yield piece, row["xml_score"], row["midi_performance"], row["match_file"]


def batik(root: Path):
    # scores_edited contain only the repeats the performances play (dataset README)
    for match in sorted((root / "match").glob("*.match")):
        s = match.stem
        yield s, f"scores_edited/{s}.musicxml", f"midi/{s}.mid", f"match/{s}.match"


def vienna4x22(root: Path):
    for match in sorted((root / "match").glob("*.match")):
        s = match.stem
        yield s, f"musicxml/{s.rsplit('_p', 1)[0]}.musicxml", f"midi/{s}.mid", f"match/{s}.match"


PIECES = {"nasap": nasap, "batik": batik, "vienna4x22": vienna4x22}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--dest", type=Path, required=True)
    parser.add_argument("--datasets", default=",".join(DATASETS))
    parser.add_argument("--limit", type=int, help="pieces per dataset (evenly spread)")
    args = parser.parse_args()
    dest = args.dest.resolve()

    for name in args.datasets.split(","):
        meta = DATASETS[name]
        root = dest / name
        fetch(meta["repo"], meta["commit"], root)
        pieces = sorted(PIECES[name](root))
        if args.limit and len(pieces) > args.limit:
            pieces = [pieces[i * len(pieces) // args.limit] for i in range(args.limit)]
        lines = [f"# {meta['name']} @ {meta['commit']} ({meta['license']}); generated by fetch.py", ""]
        for piece, score, perf, gt in pieces:
            lines += [
                "[[pieces]]",
                f'dataset = "{name}"',
                f'piece = "{piece}"',
                f'score = "{(root / score).as_posix()}"',
                f'performance = "{(root / perf).as_posix()}"',
                f'ground_truth = "{(root / gt).as_posix()}"',
                "",
            ]
        (dest / f"{name}.toml").write_text("\n".join(lines), encoding="utf-8")
        print(f"{name}: {len(pieces)} pieces -> {dest / f'{name}.toml'}")


if __name__ == "__main__":
    main()
